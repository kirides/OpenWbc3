            "AENX", "AEOX", "AWNX", "AWJX", "AKNX", "AKOX", "AEEX", "AAJX", "AADE", "AVJX", "ARCX", "AGFL", "AKJX", "ALMX" } })
        set("POMC", { mercenaries = { "AHGX", "ADGX", "AUGX", "ABGX", "AMGX", "AOGX", "AFGX", "AAGX", "AVGX", "ARGX", "ALGX", "AGGX", "AEGX",
            "AWGX", "AKGX" } })
        for id, skill in pairs({ RVIV = 61, RARB = 62, RCIE = 63, RMOR = 64, RMAN = 65 }) do set(id, { runeSkill = skill }) end
        set("PQKN", { questFoes = {
            { "AUGX", "undead" }, { "AKGX", "darkelf" }, { "AOGX", "orc" }, { "AVGX", "daemon" }, { "ARGX", "swarm" }, { "AGGX", "plaguelord" },
            { "AUAX", "undead" }, { "AKOX", "darkelf" }, { "AOJX", "orc" }, { "AVDX", "daemon" }, { "ARCX", "swarm" }, { "AGPY", "plaguelord" },
            { "AUMX", "undead" }, { "AKNX", "darkelf" }, { "AGCY", "plaguelord" }, { "AGHY", "plaguelord" },
            { "AAEE" }, { "AAEF" }, { "AAEA" }, { "AAEW" } } })
    end,
}
