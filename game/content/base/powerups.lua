    --   research     casting levels a Spell / Arcane Research gives (the research routine FUN_00438180)
    --   oneShot      bought over and over, never owned: the research and mercenary power-ups (the power-up routine FUN_00436500)
    --   mercenaries  the units a mercenary power-up can hire (the mercenary routine FUN_004382d0: a random entry of the level's list; the
    --                lists are data of the binary, 28 / 27 / 15 types, the original gives them any race)
    --   runeSkill    hero skill whose levels make a rune 10 % cheaper each: Life -> Vivos, Forest -> Arbos, Sky -> Cielos, Death ->
    --                Mortos, Arcane -> Manos (read from the cost function of the 1.04 binary, FUN_0040b6b0); Animos has none
    --   questFoes    the Knight's Quest foes on offer (the quest offer FUN_00438d40): the first four entries that fit, { unit,
    --                race id }: a race entry once for every other side of that race in the game, no race = always
    ---@param content Content
    patch = function(content)
        local function set(id, fields)
            local rec = content.powerup[id]
            if not rec then content.warn("power-up data names %s, which has no record", id) return end
            for k, v in pairs(fields) do rec[k] = v end
        end
        for id, cells in pairs({ PRA0 = 2, PRA1 = 1, PRA2 = 1, PDS0 = 2, PDS1 = 2 }) do set(id, { view = cells }) end
        for _, id in ipairs({ "PSPR", "PARR", "POMA", "POMB", "POMC" }) do set(id, { oneShot = true }) end
        set("PSPR", { research = 1 })     -- Spell Research and Arcane Research: casting levels for a random sphere (FUN_00438180)
        set("PARR", { research = 3 })
        set("POMA", { mercenaries = { "AHFX", "AHMX", "ADIX", "ADMX", "AUJX", "AUKX", "ABCX", "ABIX", "AMIX", "AMNX", "AOIX", "AOCX", "AEMX",
            "AECX", "AWIX", "AWCX", "AKMX", "AKCX", "AFNX", "AFIX", "AAIX", "AVIX", "AAIM", "ASSC", "ARMX", "AGGZ", "AGPC", "ALIX" } })
