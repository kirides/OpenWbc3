-- Reader for .xcr resource archives.
--
-- Layout (little-endian):
--   header    : char id[20] ("xcr File 1.00"), int32 count, uint32 totalSize
--   directory : count * 532-byte records
--       char name[256], char srcPath[256], uint32 offset, uint32 size,
--       int32 type, uint32 crc, uint8 checkCrc, uint8 encrypted, 2 pad
--   data      : raw entry bytes at the given absolute offsets
-- Encrypted entries use a fixed byte substitution (see buildTables).
local ffi = require("ffi")
local bin = require("src.core.bin")

local M = {}

local HEADER_SIZE = 28
local ENTRY_SIZE = 532

-- The substitution table is generated by a 16-bit LCG seeded with 728;
-- each step yields a byte value not used before.
local dec = ffi.new("uint8_t[256]")
do
    local used = {}
    local state = 728
    for i = 0, 255 do
        local r
        repeat
            state = (25173 * state + 13849) % 65536
            r = math.floor(state * 256 / 65535)
            if r > 255 then r = 255 end
        until not used[r]
        used[r] = true
        dec[r] = i
    end
end

---@param data string
---@return string
function M.decrypt(data)
    local n = #data
    local buf = ffi.new("uint8_t[?]", n)
    ffi.copy(buf, data, n)
    for i = 0, n - 1 do buf[i] = dec[buf[i]] end
    return ffi.string(buf, n)
end

---@class XcrEntry
---@field name string      entry name as stored (lookups are case-insensitive)
---@field offset integer   absolute file offset of the data
---@field size integer
---@field encrypted boolean

-- An opened archive: the directory is read up front, the data on demand through one kept-open handle.
---@class XcrArchive
---@field path string
---@field key string?                     path relative to the game folder, set by vfs.mount
---@field entries XcrEntry[]              in directory order
---@field byName table<string, XcrEntry>  lower-cased name -> first entry of that name
---@field handle file*?
local Archive = {}
Archive.__index = Archive

---@param path string
---@return XcrArchive? archive
---@return string? err
function M.open(path)
    local f, err = io.open(path, "rb")
    if not f then return nil, err end
    local head = f:read(HEADER_SIZE)
    if not head or #head < HEADER_SIZE or head:sub(1, 13):lower() ~= "xcr file 1.00" then
        f:close()
        return nil, "not an xcr archive: " .. path
    end
    local count = bin.i32(head, 20)
    local dir = f:read(count * ENTRY_SIZE)
    if not dir or #dir < count * ENTRY_SIZE then
        f:close()
        return nil, "truncated directory: " .. path
    end
    local r = bin.reader(dir)
    local entries, byName = {}, {}
    for i = 1, count do
        local base = (i - 1) * ENTRY_SIZE
        r:seek(base)
        local name = r:fixstr(256)
        r:seek(base + 512)
        local e = {
            name = name,
            offset = r:u32(),
            size = r:u32(),
        }
        r:seek(base + 529)
        e.encrypted = r:u8() ~= 0
        entries[i] = e
        local key = name:lower()
        if not byName[key] then byName[key] = e end   -- first match wins
    end
    f:close()
    return (setmetatable({ path = path, entries = entries, byName = byName }, Archive))
end

---@param name string
---@return boolean
function Archive:has(name)
    return self.byName[name:lower()] ~= nil
end

---@param name string
---@return XcrEntry?
function Archive:entry(name)
    return self.byName[name:lower()]
end

-- The (decrypted) bytes of an entry, given by name or as an entry record; nil when there is no such entry.
---@param name string|XcrEntry
---@return string?
function Archive:read(name)
    local e = type(name) == "table" and name or self.byName[(name --[[@as string]]):lower()]
    if not e then return nil end
    local f = self.handle
    if not f then
        f = assert(io.open(self.path, "rb"))
        self.handle = f
    end
    f:seek("set", e.offset)
    local data = f:read(e.size) or ""
    if e.encrypted then data = M.decrypt(data) end
    return data
end

function Archive:close()
    if self.handle then self.handle:close() self.handle = nil end
end

return M
