-- Generates game/src/game/formationdata.lua: the original's formation slot tables, read from the game binary.
--   pwsh tools/dev/love.ps1 -- --selftest --lua tools/dev/genformations.lua "<path of Battlecry III-orig.exe>" game/src/game/formationdata.lua
-- (run from the repository root; the exe is the 1.04 binary, md5 d8d6debd538857fec26a133f483342da, the one Ghidra
-- shows as "Battlecry III.exe"). The formation table lives at VA 0x005FBC9C: 8 formations x 32 rows x 32 slots of
-- two little-endian int16 (x, y); row 32 - n holds the n slots of a group of n units. The unused slots after the n-th
-- are zero and are not written out.
local exePath, outPath = ...
assert(exePath and outPath, "usage: genformations.lua <exe> <output.lua>")
local f = assert(io.open(exePath, "rb"))
local data = f:read("*a")
f:close()

---@param o integer file offset
---@return integer
local function u16(o) return data:byte(o + 1) + data:byte(o + 2) * 256 end
---@param o integer file offset
---@return integer
local function u32(o) return u16(o) + u16(o + 2) * 65536 end
---@param o integer file offset
---@return integer
local function s16(o) local v = u16(o) return v >= 32768 and v - 65536 or v end

-- virtual address -> file offset through the PE section table
local pe = u32(0x3c)
local nsec, optSize = u16(pe + 6), u16(pe + 20)
local base = u32(pe + 24 + 28)
---@param va integer virtual address
---@return integer
local function fileOffset(va)
    for i = 0, nsec - 1 do
        local o = pe + 24 + optSize + i * 40
        local vsize, vaddr, rsize, raw = u32(o + 8), u32(o + 12), u32(o + 16), u32(o + 20)
        local rva = va - base
        if rva >= vaddr and rva < vaddr + math.min(vsize, rsize) then return raw + rva - vaddr end
    end
    error("address not in the file")
end

local KINDS = { "block", "circle", "wedge", "skirmish", "line", "column", "wideline", "doublefile" }
local TABLE = 0x005FBC9C
local start = fileOffset(TABLE)

local out = {}
---@param s string a line of the output
local function w(s) out[#out + 1] = s end
w("-- The original's formation slot tables, read from its executable.")
w("-- Generated by tools/dev/genformations.lua from the 1.04 executable, table at VA 0x005FBC9C: 8 formations x 32 rows x")
w("-- 32 slots of (x, y) int16. slots[kind][n] is the flat list x1, y1, x2, y2 ... of the n slots of a group of n units")
w("-- (the original's row 32 - n), in the order the original hands them out (ranged units first). Offsets are cells in the")
w("-- formation's own frame: +y is the front for the direction BOTTOM; see formation.lua for the eight directions.")
w("local M = { slots = {} }")
local total = 0
for t, kind in ipairs(KINDS) do
    w(("M.slots.%s = {"):format(kind))
    for n = 1, 32 do
        local row, parts = 32 - n, {}
        for s = 0, n - 1 do
            local o = start + (((t - 1) * 32 + row) * 32 + s) * 4
            parts[#parts + 1] = s16(o)
            parts[#parts + 1] = s16(o + 2)
            total = total + 1
        end
        w(("    [%d] = { %s },"):format(n, table.concat(parts, ", ")))
    end
    w("}")
end
w("return M")
local o = assert(io.open(outPath, "wb"))
o:write(table.concat(out, "\n"), "\n")
o:close()
print(("[info] formation tables: %d slots written to %s"):format(total, outPath))
